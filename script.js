const productCard = document.querySelector("#product-card");

if (productCard) {
  let dragging = false;
  let startX = 0;
  let rotation = -24;

  productCard.addEventListener("pointerdown", event => {
    dragging = true;
    startX = event.clientX;
    productCard.classList.add("is-dragging");
    productCard.setPointerCapture(event.pointerId);
  });

  productCard.addEventListener("pointermove", event => {
    if (!dragging) return;

    const difference = event.clientX - startX;

    rotation += difference * 0.35;
    startX = event.clientX;

    productCard.style.setProperty(
      "--drag-rotation",
      `${rotation}deg`
    );
  });

  productCard.addEventListener("pointerup", () => {
    dragging = false;
    productCard.classList.remove("is-dragging");
  });

  productCard.addEventListener("pointercancel", () => {
    dragging = false;
    productCard.classList.remove("is-dragging");
  });
}

const reviewForm = document.querySelector("#review-form");
const savedReviews = document.querySelector("#saved-reviews");
const ratingSummary = document.querySelector("#rating-summary");

let reviews = JSON.parse(
  localStorage.getItem("orbit-reviews") || "[]"
);

function updateReviewSummary() {
  if (!ratingSummary) return;

  const counts = [1, 2, 3, 4, 5].map(rating => {
    return reviews.filter(
      review => Number(review.rating) === rating
    ).length;
  });

  const total = reviews.length;

  ratingSummary.innerHTML = counts
    .map((count, index) => {
      const rating = index + 1;
      const percent = total
        ? Math.round((count / total) * 100)
        : 0;

      return `
        <div>
          <span>${rating}★</span>
          <i><b style="width:${percent}%"></b></i>
          <strong>${count}</strong>
        </div>
      `;
    })
    .join("");
}

function renderReviews() {
  if (!savedReviews) return;

  if (!reviews.length) {
    savedReviews.innerHTML = "";
    return;
  }

  savedReviews.innerHTML = reviews
    .slice(-3)
    .reverse()
    .map(review => {
      return `
        <article>
          <strong>${review.reviewer}</strong>
          <span>${"★".repeat(Number(review.rating))}</span>
          <p>${escapeHtml(review.text)}</p>
        </article>
      `;
    })
    .join("");
}

function escapeHtml(text) {
  const div = document.createElement("div");
  div.textContent = text;
  return div.innerHTML;
}

