let currentLanguage = localStorage.getItem("orbit-language") || "hu";

const serviceCards = document.querySelectorAll(".service");
const essentialCards = document.querySelectorAll(".essential-card");

function getTranslation(object, path) {
  return path.split(".").reduce((value, key) => {
    return value && value[key] !== undefined ? value[key] : "";
  }, object);
}

function translatePage() {
  const dictionary = translations[currentLanguage];

  document.documentElement.lang = currentLanguage;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    const value = getTranslation(dictionary, key);

    if (value !== "") {
      element.innerHTML = value;
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    const key = element.dataset.i18nPlaceholder;
    const value = getTranslation(dictionary, key);

    if (value !== "") {
      element.placeholder = value;
    }
  });

  const subject = document.querySelector("#quote-subject");

  if (subject) {
    subject.value = dictionary.quote.subject;
  }

  document.querySelectorAll(".lang").forEach(button => {
    button.classList.toggle(
      "active",
      button.dataset.lang === currentLanguage
    );
  });

  updateServiceDetail();
  updateEssentialDetail();
  updateReviewSummary();
}

function setLanguage(language) {
  if (!translations[language]) return;

  currentLanguage = language;
  localStorage.setItem("orbit-language", language);
  translatePage();
}

document.querySelectorAll(".lang").forEach(button => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.lang);
  });
});

function scrollToElement(element) {
  if (!element) return;

  const top =
    element.getBoundingClientRect().top +
    window.scrollY -
    105;

  window.scrollTo({
    top,
    behavior: "smooth"
  });
}

let selectedService = null;

function selectService(serviceName, shouldScroll = true) {
  const service = translations[currentLanguage].services[serviceName];

  if (!service) return;

  selectedService = serviceName;

  serviceCards.forEach(card => {
    card.classList.toggle(
      "selected",
      card.dataset.service === serviceName
    );
  });

  document.querySelector("#detail-title").innerHTML =
    service.detailTitle;

  document.querySelector("#detail-text").innerHTML =
    service.detailText;

  const list = document.querySelector("#detail-list");

  list.innerHTML = service.list
    .map(item => `<li>${item}</li>`)
    .join("");

  const art = document.querySelector("#detail-art");

  art.innerHTML = `
    <span>${service.detailTitle.toUpperCase()}</span>
  `;

  art.dataset.service = serviceName;

  if (shouldScroll) {
    setTimeout(() => {
      scrollToElement(document.querySelector("#service-detail"));
    }, 80);
  }
}

function updateServiceDetail() {
  if (selectedService) {
    selectService(selectedService, false);
  }
}

serviceCards.forEach(card => {
  card.addEventListener("click", () => {
    selectService(card.dataset.service, true);
  });

  card.addEventListener("keydown", event => {
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      selectService(card.dataset.service, true);
    }
  });
});

